"""The layout of a figure: which series are drawn in which panel.

A figure is a vertical stack of panels that share one time axis. A ``Panel`` is one
subplot and holds one or more ``Line`` objects, each of which draws one column of the
data. ``as_panels`` converts the shorthand forms of a layout to a list of ``Panel``
objects:

- a column name, or a ``Line``, defines a panel with one line;
- a ``(column, title)`` pair defines a panel with one line and a title;
- a ``{column: title}`` dict defines one panel per column;
- a single column name, ``Line``, or ``Panel`` in place of a sequence defines a layout
  of one panel.

A panel with several lines is always written as ``Panel([...])``. The reasons for these
rules, and the check of ambiguous pairs, are given in the docstring of ``as_panels``.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from tspanels.annotations import Annotation


@dataclass
class Line:
    """One column of the data, drawn as a line in a panel.

    Attributes
    ----------
    column : str
        Name of the column of the data that holds the series.
    label : str, optional
        Name of the series in the panel legend. A line without a label is not listed
        in the legend.
    color : str, optional
        Line color. None assigns the next color of ``Style.series`` that no other line
        of the same panel uses explicitly. A field name of ``Style``, such as
        ``"alert"`` or ``"series[2]"``, takes that color from the figure's style.
    linewidth : float
        Line width in points.
    linestyle : str
        Matplotlib line style, for example ``"-"`` (solid) or ``"--"`` (dashed).
    """

    column: str
    label: str | None = None
    color: str | None = None
    linewidth: float = 0.8
    linestyle: str = "-"


@dataclass(init=False)
class Panel:
    """One subplot: lines that share a y axis, and the annotations drawn in this subplot only.

    A legend is drawn above the panel when the panel has two or more labeled items
    (lines, annotations, or gap markers), and in its upper right corner when it has one.

    Attributes
    ----------
    lines : sequence of Line or str
        The series of the panel, drawn in this order. A string is converted to
        ``Line(string)``; a single string or Line is accepted in place of a sequence.
    title : str, optional
        Panel title, placed above the panel on the left. None uses, for a panel with
        one line, that line's label, or its column name when the label is also None;
        a panel with several lines then has no title.
    annotations : sequence of Annotation
        Annotations drawn in this panel only, for example ``RefLine`` or ``Points``.
    height : float
        Height relative to the other panels: a panel with ``height=2`` is twice as tall
        as a panel with ``height=1``.
    """

    lines: list[Line]
    title: str | None
    annotations: Sequence[Annotation]
    height: float

    def __init__(self, lines: Sequence[Line | str] | Line | str, title: str | None = None,
                 annotations: Sequence[Annotation] = (), height: float = 1.0):
        """Store the attributes, converting ``lines`` to a list of Line objects.

        A single string or Line becomes a one-item list, and each string ``s`` becomes
        ``Line(s)``. The constructor is written out, instead of generated by
        ``dataclass``, so that the attribute ``lines`` has the type ``list[Line]`` while
        the argument also accepts strings.
        """
        if isinstance(lines, (str, Line)):
            lines = [lines]
        self.lines = [Line(x) if isinstance(x, str) else x for x in lines]
        self.title = title
        self.annotations = annotations
        self.height = height

    def columns(self) -> list[str]:
        """Return the column names of the panel's lines, in drawing order."""
        return [line.column for line in self.lines]


_FORMS = ("a Panel, a Line, a column name, or a (column, title) pair; "
          "several lines in one panel are written as Panel([...])")


def as_panels(spec, columns=None) -> list[Panel]:
    """Convert a layout given in any accepted form to a list of Panel objects.

    Design decisions
    ----------------
    - A single column name, ``Line``, or ``Panel`` given in place of a sequence is a
      layout of one panel. A string is never iterated, because iterating it would
      produce one panel per character.
    - A tuple is always a ``(column, title)`` pair. A panel with several lines is
      written as ``Panel([...])``, never as a tuple or a list of column names; every
      other form of item raises ``TypeError`` rather than being guessed.
    - The pair ``("a", "b")`` is ambiguous when ``b`` is also a column: it may be meant
      as a title or as a second line. When ``columns`` is given (``plot_panels`` passes
      the data's columns), a pair whose title is the name of another column therefore
      raises ``ValueError``. A title equal to the pair's own column, as in
      ``("volume", "volume")``, is not ambiguous and is accepted.
    - In a ``{column: title}`` dict the value is a title by construction, so a dict
      value is never checked against the columns.

    Parameters
    ----------
    spec : dict, sequence, str, Line, or Panel
        A ``{column: title}`` dict, which yields one panel per column in the order of
        the dict; a sequence whose items are each a Panel (used as is), a Line or a
        column name (a panel with that one line), or a ``(column, title)`` pair; or a
        single column name, Line, or Panel, which yields one panel.
    columns : collection of str, optional
        The column names of the data. When given, each ``(column, title)`` pair of a
        sequence is checked for the ambiguity described above. None skips the check.

    Returns
    -------
    list of Panel
        One Panel per subplot, in order from top to bottom.

    Raises
    ------
    TypeError
        If an item has none of the accepted forms, for example a list of column names,
        a tuple that is not a pair of strings, or a number.
    ValueError
        If ``columns`` is given and the title of a ``(column, title)`` pair is the name
        of another column.
    """
    if isinstance(spec, (str, Line, Panel)):
        spec = [spec]
    if isinstance(spec, Mapping):
        return [_pair_panel(item) for item in spec.items()]
    known = set(columns) if columns is not None else set()
    panels = []
    for item in spec:
        if isinstance(item, Panel):
            panels.append(item)
        elif isinstance(item, (str, Line)):
            panels.append(Panel([item]))
        elif isinstance(item, tuple):
            panel = _pair_panel(item)
            column, title = item
            if title in known and title != column:
                raise ValueError(
                    f"the pair {item!r} is read as (column, title), but {title!r} is also a "
                    f"column of the data; write Panel([{column!r}, {title!r}]) for two lines in "
                    f"one panel, or Panel({column!r}, title={title!r}) for a title"
                )
            panels.append(panel)
        else:
            raise TypeError(f"a layout item must be {_FORMS}, not {item!r}")
    return panels


def _pair_panel(item: tuple) -> Panel:
    """Return the one-line Panel of a ``(column, title)`` pair, checking its form.

    Raises
    ------
    TypeError
        If ``item`` is not a pair of a column name and a title (a string or None).
    """
    if len(item) != 2 or not isinstance(item[0], str) or not isinstance(item[1], (str, type(None))):
        raise TypeError(f"a layout item must be {_FORMS}, not {item!r}")
    column, title = item
    return Panel([column], title=title)
